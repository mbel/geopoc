/** Années distractrices plausibles : l'écart dépend de l'époque. */
function yearWrong(rng: Rng, y: number): string[] {
  const offs = y < 1500 ? [-100, -50, -25, -10, -5, 5, 10, 25, 50, 100] : y < 1800 ? [-20, -10, -5, -3, 3, 5, 10, 20, 30] : [-10, -5, -3, -2, -1, 1, 2, 3, 5, 10];
  return sample(rng, offs, 3).map((o) => String(y + o));
}

